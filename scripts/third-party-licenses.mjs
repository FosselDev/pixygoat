// Writes THIRD_PARTY_LICENSES.md from package-lock.json: every production
// dependency of the workspaces with its version, license and repository.
// license-checker only sees the root package in an npm workspace, hence this.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const lock = JSON.parse(readFileSync(resolve(root, "package-lock.json"), "utf8"));
const rows = [];
const allowed = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "BlueOak-1.0.0", "CC0-1.0", "Unlicense", "Python-2.0", "(MIT OR CC0-1.0)", "MIT-0"]);
const flagged = [];

for (const [path, info] of Object.entries(lock.packages)) {
  if (!path.startsWith("node_modules/") || info.dev || info.link) continue;
  const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
  let license = info.license;
  let repo = "";
  const pkgJson = resolve(root, path, "package.json");
  if (existsSync(pkgJson)) {
    try {
      const pkg = JSON.parse(readFileSync(pkgJson, "utf8"));
      license ??= typeof pkg.license === "string" ? pkg.license : pkg.license?.type;
      repo = typeof pkg.repository === "string" ? pkg.repository : (pkg.repository?.url ?? pkg.homepage ?? "");
    } catch {
      /* ignore */
    }
  }
  license ??= "UNKNOWN";
  rows.push({ name, version: info.version, license, repo: repo.replace(/^git\+/, "").replace(/\.git$/, "") });
  if (!allowed.has(license)) flagged.push(`${name}@${info.version}: ${license}`);
}

rows.sort((a, b) => a.name.localeCompare(b.name));
const md = [
  "# Third-party licenses",
  "",
  "Production dependencies of PixyGoat (generated by `npm run licenses`).",
  "",
  "| Package | Version | License | Source |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`),
  "",
].join("\n");
writeFileSync(resolve(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`${rows.length} packages written to THIRD_PARTY_LICENSES.md`);
if (flagged.length) {
  console.log("Licenses outside the permissive allowlist, check before release:");
  for (const f of flagged) console.log("  " + f);
}
